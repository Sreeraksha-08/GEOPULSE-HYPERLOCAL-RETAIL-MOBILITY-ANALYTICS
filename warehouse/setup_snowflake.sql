-- 1. Create the GeoPulse database
CREATE DATABASE IF NOT EXISTS GEOPULSE_DB;

-- 2. Create the RAW schema
CREATE SCHEMA IF NOT EXISTS GEOPULSE_DB.RAW;

-- 3. Create a small warehouse to minimize trial usage
CREATE WAREHOUSE IF NOT EXISTS GEOPULSE_WH
    WITH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- 4. Select the warehouse, database and schema
USE WAREHOUSE GEOPULSE_WH;
USE DATABASE GEOPULSE_DB;
USE SCHEMA RAW;

-- 5. Verify the setup
SELECT CURRENT_DATABASE(),
       CURRENT_SCHEMA(),
       CURRENT_WAREHOUSE(),
       CURRENT_ROLE();

SHOW WAREHOUSES LIKE 'GEOPULSE_WH';

SHOW DATABASES LIKE 'GEOPULSE_DB';

SHOW SCHEMAS LIKE 'RAW' IN DATABASE GEOPULSE_DB;