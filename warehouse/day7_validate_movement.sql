-- GeoPulse Day 7: Snowflake data validation

USE WAREHOUSE GEOPULSE_WH;
USE DATABASE GEOPULSE_DB;
USE SCHEMA RAW;

-- Check total records, devices and null values
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT DEVICE_ID) AS UNIQUE_DEVICES,
    COUNT_IF(TIMESTAMP IS NULL) AS NULL_TIMESTAMPS,
    COUNT_IF(DEVICE_ID IS NULL) AS NULL_DEVICE_IDS
FROM RAW_DEVICE_MOVEMENT;

-- Check all activity categories
SELECT
    ACTIVITY,
    COUNT(*) AS RECORD_COUNT
FROM RAW_DEVICE_MOVEMENT
GROUP BY ACTIVITY
ORDER BY ACTIVITY;

-- Check exact duplicate records
SELECT COALESCE(SUM(ROW_COUNT - 1), 0) AS DUPLICATE_ROWS
FROM (
    SELECT COUNT(*) AS ROW_COUNT
    FROM RAW_DEVICE_MOVEMENT
    GROUP BY TIMESTAMP, DEVICE_ID, ZONE_ID,
             ZONE_TYPE, ACTIVITY, LATITUDE, LONGITUDE
    HAVING COUNT(*) > 1
);

-- Preview loaded data
SELECT *
FROM RAW_DEVICE_MOVEMENT
LIMIT 10;